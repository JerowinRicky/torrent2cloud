import uuid
from typing import Optional
from fastapi import APIRouter, Depends, Header, Request, status
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.database import get_db
from app.api.deps import get_current_user
from app.models.user import User
from app.schemas.download import (
    DownloadLinkGenerateRequest,
    DownloadLinkResponse,
    DownloadLinkListResponse,
    MultiFileDownloadRequest,
    MultiFileDownloadResponse,
)
from app.services.download_service import DownloadService

router = APIRouter()

@router.post("/generate", response_model=DownloadLinkResponse, status_code=status.HTTP_201_CREATED)
async def generate_download_link(
    payload: DownloadLinkGenerateRequest,
    request: Request,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """Generates an expiring, cryptographically signed direct HTTPS download link for a file."""
    base_url = str(request.base_url).rstrip("/")
    return await DownloadService.generate_download_link(
        db=db,
        user=current_user,
        file_id=payload.file_id,
        expires_in_hours=payload.expires_in_hours,
        base_url=base_url
    )

@router.post("/generate-batch", response_model=MultiFileDownloadResponse)
async def generate_batch_download_links(
    payload: MultiFileDownloadRequest,
    request: Request,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """Generates individual signed download links for multiple files in bulk."""
    base_url = str(request.base_url).rstrip("/")
    links = await DownloadService.generate_multi_download_links(
        db=db,
        user=current_user,
        file_ids=payload.file_ids,
        expires_in_hours=payload.expires_in_hours,
        base_url=base_url
    )
    return MultiFileDownloadResponse(links=links)

@router.get("/links", response_model=DownloadLinkListResponse)
async def list_active_download_links(
    request: Request,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """Lists active, unexpired download links generated by the current user."""
    base_url = str(request.base_url).rstrip("/")
    links = await DownloadService.list_user_links(db=db, user=current_user, base_url=base_url)
    return DownloadLinkListResponse(items=links, total=len(links))

@router.delete("/links/{link_id}", status_code=status.HTTP_200_OK)
async def revoke_download_link(
    link_id: uuid.UUID,
    current_user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db)
):
    """Revokes a signed download link, immediately disabling access."""
    await DownloadService.revoke_link(db=db, user=current_user, link_id=link_id)
    return {"status": "revoked", "link_id": link_id}

@router.get("/file/{token}", summary="Download file directly with byte-range resume support")
async def download_file_direct(
    token: str,
    range: Optional[str] = Header(None, alias="Range"),
    db: AsyncSession = Depends(get_db)
):
    """
    Publicly accessible streaming download endpoint.
    Protected by HMAC-SHA256 signature verification and expiration check.
    Supports HTTP 206 Partial Content range requests for resumed downloads.
    """
    return await DownloadService.stream_download(
        db=db,
        token=token,
        range_header=range
    )
